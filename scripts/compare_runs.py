#!/usr/bin/env python3
"""Compare two evaluation runs of the same synthetic split and render before/after panels.

    uv run --frozen python scripts/compare_runs.py --data data/synthetic/d21_test \
        --a results/d21/test_baseline --b results/d21/test_masked \
        --config-a configs/baseline_no_marker_mask.json --out results/d21/test_comparison

Writes comparison.md (metrics side by side, every case whose outcome or region count
changed) and before_after/*.jpg (run A panel above run B panel) for the changed cases.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from loopcheck.config import PipelineConfig  # noqa: E402
from loopcheck.evaluate import _panel, classify_outcome, evaluate_case  # noqa: E402


def _get(d: dict, path: str):
    for k in path.split("."):
        d = d[k] if d is not None else None
    return d


ROWS = [
    ("Image-level precision", "image_level.precision"),
    ("Image-level recall", "image_level.recall"),
    ("Image-level F1", "image_level.f1"),
    ("FPR on good (perturbed) images", "false_positive_rate_nominal"),
    ("False regions per good image", "false_regions_per_nominal_image"),
    ("Region recall @ IoU>=0.3", "region_recall_iou30"),
    ("Region precision @ IoU>=0.3 (defect cases)", "region_precision_iou30_defect_cases"),
    ("Marker-attributable FP regions (all)", "markers.marker_fp_regions_total"),
    ("  ... on good images", "markers.marker_fp_regions_nominal"),
    ("  ... in defect cases", "markers.marker_fp_regions_defect_cases"),
    ("Good images with a marker-attributable region", "markers.nominal_images_with_marker_fp"),
    ("Unmatched regions in defect cases (all causes)", "markers.unmatched_regions_defect_cases"),
    ("Registration success (good + defect cases)", "registration.success_rate"),
    ("Correct rejection (registration-fail cases)", "registration.correct_rejection_rate"),
    ("Incorrect alignments (corner err > 2 px)", "incorrect_alignments.count"),
    ("Different tray: registration failed", "different_tray.registration_failed"),
    ("Different tray: flagged", "different_tray.registered_and_flagged"),
    ("Different tray: UNSAFE (no candidates)", "different_tray.registered_no_candidates_UNSAFE"),
]


def fmt(v):
    return "n/a" if v is None else (f"{v:.3f}" if isinstance(v, float) else str(v))


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", type=Path, required=True)
    p.add_argument("--a", type=Path, required=True, help="evaluation dir of run A (before)")
    p.add_argument("--b", type=Path, required=True, help="evaluation dir of run B (after)")
    p.add_argument("--config-a", type=Path)
    p.add_argument("--config-b", type=Path)
    p.add_argument("--label-a", default="baseline (no marker mask)")
    p.add_argument("--label-b", default="marker mask")
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args(argv)

    ma, mb = (json.loads((d / "metrics.json").read_text()) for d in (args.a, args.b))
    ra = {r["id"]: r for r in json.loads((args.a / "per_case.json").read_text())}
    rb = {r["id"]: r for r in json.loads((args.b / "per_case.json").read_text())}
    manifest = {c["id"]: c for c in json.loads((args.data / "manifest.json").read_text())["cases"]}

    lines = [f"# Run comparison: {args.data.name} (seed {ma['data_seed']})", "",
             "**SYNTHETIC DATA.** Same cases, two configurations. Generated by `scripts/compare_runs.py`.", "",
             f"| Metric | {args.label_a} | {args.label_b} |", "|---|---|---|"]
    lines += [f"| {name} | {fmt(_get(ma, path))} | {fmt(_get(mb, path))} |" for name, path in ROWS]
    lines += ["", "## Near vs distant defects", "", f"| Group | {args.label_a}: cases, image recall / GT, region recall | {args.label_b} |", "|---|---|---|"]
    for g in ma["defects_near_vs_distant"]:
        a, b = ma["defects_near_vs_distant"][g], mb["defects_near_vs_distant"][g]
        lines.append(f"| {g} | {a['cases']}, {fmt(a['image_recall'])} / {a['gt_boxes']}, {fmt(a['region_recall_iou30'])} | {b['cases']}, {fmt(b['image_recall'])} / {b['gt_boxes']}, {fmt(b['region_recall_iou30'])} |")

    changed = [k for k in ra if ra[k]["outcome"] != rb[k]["outcome"] or ra[k]["n_regions"] != rb[k]["n_regions"]]
    lines += ["", "## Cases whose outcome or region count changed", "",
              "| Case | Outcome A -> B | Regions A -> B | Marker-attrib. A -> B | GT IoU A -> B | Marker gap of GT (px) |", "|---|---|---|---|---|---|"]
    for k in changed:
        a, b = ra[k], rb[k]
        lines.append(f"| {k} | {a['outcome']} -> {b['outcome']} | {a['n_regions']} -> {b['n_regions']} | {a['marker_fp_regions']} -> {b['marker_fp_regions']} | {a['gt_ious']} -> {b['gt_ious']} | {manifest[k].get('gt_marker_gap_px')} |")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "comparison.md").write_text("\n".join(lines) + "\n")

    panels = args.out / "before_after"
    panels.mkdir(exist_ok=True)
    cfgs = [PipelineConfig.from_json(c) if c else PipelineConfig() for c in (args.config_a, args.config_b)]
    for k in changed:
        tiles = []
        for label, cfg in zip((args.label_a, args.label_b), cfgs):
            row, art = evaluate_case(manifest[k], args.data, cfg)
            row["outcome"] = classify_outcome(row)
            t = _panel(manifest[k], row, art)
            cv2.rectangle(t, (0, 0), (t.shape[1], 24), (40, 40, 40), -1)
            cv2.putText(t, f"{label}: {row['outcome']}", (8, 17), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (255, 255, 255), 1, cv2.LINE_AA)
            tiles.append(t)
        cv2.imwrite(str(panels / f"{k}.jpg"), np.vstack(tiles), [cv2.IMWRITE_JPEG_QUALITY, 80])
    print(f"{len(changed)} changed cases; wrote {args.out}/comparison.md and {len(changed)} panels")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
